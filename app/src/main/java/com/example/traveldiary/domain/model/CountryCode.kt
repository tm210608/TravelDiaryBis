package com.example.traveldiary.domain.model

import java.text.Normalizer
import java.util.Locale

internal fun String.normalized(): String =
    Normalizer.normalize(this, Normalizer.Form.NFD)
        .replace("\\p{Mn}+".toRegex(), "")
        .lowercase(Locale.ROOT)
        .trim()

fun countryCodeOf(country: String): String? {
    val norm = country.normalized()
    if (norm.isEmpty()) return null
    return countryToIso3[norm] ?: norm.take(3).uppercase(Locale.ROOT)
}

